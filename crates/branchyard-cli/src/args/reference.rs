//! The command reference in `docs/cli-reference.md`: every command `by help
//! all` lists, with its subcommands, usage and options, rendered as Markdown
//! from the same definitions `--help` prints. `by man --markdown` prints it,
//! `python3 tools/check.py --fix` writes it, and a test fails when the file
//! no longer matches what this renders.

use super::*;

/// The page's opening, above the global options.
const PREAMBLE: &str = "\
# Command reference

Every command `by help all` lists, with its subcommands and options, as `by`'s own definitions \
give them. This page is generated by `by man --markdown`; do not edit it by hand: \
`python3 tools/check.py --fix` rewrites it, and a test fails when it is stale. `by help COMMAND` \
prints the same text with the command's examples, and [surfaces](surfaces.md) says where each \
operation is reached outside the command line.
";

/// The Markdown reference of every visible command (see the module
/// documentation).
pub fn reference_markdown() -> String {
    on_parse_stack(|| {
        let mut cmd = build_command();
        cmd.build();
        let mut out = String::from(PREAMBLE);
        let globals: Vec<&clap::Arg> = cmd
            .get_arguments()
            .filter(|a| a.is_global_set() && !a.is_hide_set())
            .collect();
        if !globals.is_empty() {
            out.push_str("\n## Global options\n\nThese go before or after any command.\n\n");
            options_table(&globals, &mut out);
        }
        for sub in visible(&cmd) {
            section(sub, "by", &mut out);
        }
        out
    })
}

/// The subcommands `--help` lists, in its order.
fn visible(cmd: &clap::Command) -> Vec<&clap::Command> {
    let mut subs: Vec<&clap::Command> = cmd
        .get_subcommands()
        .filter(|s| !s.is_hide_set() && s.get_name() != "help")
        .collect();
    subs.sort_by_key(|s| (s.get_display_order(), s.get_name().to_owned()));
    subs
}

/// One command's section, then its subcommands' sections.
fn section(cmd: &clap::Command, parent: &str, out: &mut String) {
    let path = format!("{parent} {}", cmd.get_name());
    let depth = path.split(' ').count().min(4);
    out.push_str(&format!("\n{} `{path}`\n\n", "#".repeat(depth)));
    if let Some(about) = cmd.get_long_about().or_else(|| cmd.get_about()) {
        out.push_str(about.to_string().trim());
        out.push_str("\n\n");
    }
    let usage = cmd.clone().bin_name(&path).render_usage().to_string();
    let usage = usage.trim().trim_start_matches("Usage:").trim();
    out.push_str(&format!("```text\n{usage}\n```\n"));
    let own: Vec<&clap::Arg> = cmd
        .get_arguments()
        .filter(|a| !a.is_hide_set() && !a.is_global_set())
        .filter(|a| !matches!(a.get_id().as_str(), "help" | "version"))
        .collect();
    if !own.is_empty() {
        out.push('\n');
        options_table(&own, out);
    }
    for sub in visible(cmd) {
        section(sub, &path, out);
    }
}

/// A table of `args`: how each is written and what it does.
fn options_table(args: &[&clap::Arg], out: &mut String) {
    out.push_str("| Option | What it does |\n|---|---|\n");
    for arg in args {
        let help = arg
            .get_help()
            .map(|h| h.to_string())
            .unwrap_or_default()
            .split_whitespace()
            .collect::<Vec<_>>()
            .join(" ");
        let mut what = help;
        let values: Vec<String> = arg
            .get_possible_values()
            .iter()
            .filter(|v| !v.is_hide_set())
            .map(|v| format!("`{}`", v.get_name()))
            .collect();
        if !values.is_empty() {
            what.push_str(&format!(" (one of {})", values.join(", ")));
        }
        let defaults: Vec<String> = arg
            .get_default_values()
            .iter()
            .map(|v| v.to_string_lossy().into_owned())
            .filter(|v| !v.is_empty())
            .collect();
        if !defaults.is_empty() && arg.get_action().takes_values() {
            what.push_str(&format!(" (default `{}`)", defaults.join(",")));
        }
        out.push_str(&format!(
            "| `{}` | {} |\n",
            spelling(arg),
            what.replace('|', "\\|")
        ));
    }
}

/// How `arg` is written: `-n, --name <NAME>`, or `<PROMPT>` for a positional.
fn spelling(arg: &clap::Arg) -> String {
    let value = arg.get_value_names().map_or_else(
        || format!("<{}>", arg.get_id().as_str().to_uppercase()),
        |names| {
            names
                .iter()
                .map(|n| format!("<{n}>"))
                .collect::<Vec<_>>()
                .join(" ")
        },
    );
    let mut names = Vec::new();
    if let Some(short) = arg.get_short() {
        names.push(format!("-{short}"));
    }
    if let Some(long) = arg.get_long() {
        names.push(format!("--{long}"));
    }
    if names.is_empty() {
        return match arg.get_num_args().is_some_and(|n| n.max_values() > 1) {
            true => format!("{value}..."),
            false => value,
        };
    }
    match arg.get_action().takes_values() {
        true => format!("{} {value}", names.join(", ")),
        false => names.join(", "),
    }
}
