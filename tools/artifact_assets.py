#!/usr/bin/env python3
"""Generate the installed artifact-toolkit mirror and shared Rust skill assets."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
GENERATED = "// Generated by tools/artifact_assets.py; edit canonical skills or SDK sources.\n"
INDEX_BUDGET = 4096
DETAIL_INDEX_BUDGET = 8192


def check_path(path: Path, boundary: Path) -> None:
    """Refuse symlinks inside the trusted outer repository root."""
    if not path.is_relative_to(boundary):
        raise ValueError(f"asset path escapes the repository: {path}")
    for ancestor in (path, *path.parents):
        if ancestor == boundary:
            break
        if ancestor.is_symlink():
            raise ValueError(f"asset path is a symlink: {ancestor}")


def files_under(root: Path, boundary: Path) -> list[Path]:
    """Read only regular source files; refuse links rather than exporting their targets."""
    check_path(root, boundary)
    if not root.is_dir():
        raise ValueError(f"asset source is not a directory: {root}")
    found = []
    for path in sorted(root.rglob("*")):
        if "__pycache__" in path.parts or path.suffix == ".pyc":
            continue
        if path.is_symlink():
            raise ValueError(f"asset source is a symlink: {path}")
        if path.is_file():
            path.read_text(encoding="utf-8")
            found.append(path)
        elif not path.is_dir():
            raise ValueError(f"asset source is not a regular file or directory: {path}")
    return found


def identifier(value: Any, label: str) -> str:
    """Parse an installed directory name without permitting path syntax."""
    if not isinstance(value, str) or not value or any(c not in "abcdefghijklmnopqrstuvwxyz0123456789-" for c in value):
        raise ValueError(f"invalid {label}: {value!r}")
    return value


def verify_upstream(skills_root: Path, boundary: Path) -> None:
    """Check pinned reused file and license bytes locally, without fetching or installing."""
    lock = skills_root / "upstream.lock.json"
    check_path(lock, boundary)
    if not lock.exists():
        return
    if not lock.is_file():
        raise ValueError("upstream lock is not a regular file")
    value = json.loads(lock.read_text())
    if value.get("schema_version") != 1 or isinstance(value.get("schema_version"), bool):
        raise ValueError("upstream lock schema_version must be 1")
    seen = set()
    for source in value["sources"]:
        name = identifier(source["id"], "upstream source id")
        if name in seen:
            raise ValueError(f"repeated upstream source id: {name}")
        seen.add(name)
        if not re.fullmatch(r"[0-9a-f]{40}", source["revision"]):
            raise ValueError(f"upstream revision must be a full lowercase commit SHA: {name}")
        for field in ["source_sha256", "installed_sha256", "license_sha256"]:
            if not re.fullmatch(r"[0-9a-f]{64}", source[field]):
                raise ValueError(f"upstream {field} must be a lowercase SHA-256: {name}")
        if source["license"] not in {"MIT", "Apache-2.0"}:
            raise ValueError(f"unapproved upstream license: {name}")
        for field in ["path", "license_path", "installed_path", "installed_license_path"]:
            relative = Path(source[field])
            if relative.is_absolute() or not relative.parts or ".." in relative.parts:
                raise ValueError(f"upstream {field} is not a safe relative path: {name}")
        for field, hash_field in [("installed_path", "installed_sha256"), ("installed_license_path", "license_sha256")]:
            path = skills_root / source[field]
            check_path(path, boundary)
            if not path.is_file():
                raise ValueError(f"upstream {field} is not a regular installed file: {name}")
            if hashlib.sha256(path.read_bytes()).hexdigest() != source[hash_field]:
                raise ValueError(f"upstream {hash_field} mismatch: {name}")


def navigation(plugin: Path, catalog: dict[str, Any], boundary: Path) -> dict[Path, str]:
    """Derive compact root, topic and skill indexes from the existing catalog."""
    skills_root = plugin / "skills"
    topics = catalog.get(
        "topics",
        [{"id": "documents", "title": "Skills", "description": "Choose the skill for the requested task."}],
    )
    by_topic: dict[str, list[dict[str, Any]]] = {}
    for topic in topics:
        name = identifier(topic["id"], "topic id")
        if name in by_topic:
            raise ValueError(f"repeated topic id: {name}")
        by_topic[name] = []
    for skill in catalog["skills"]:
        name = skill.get("topic", "documents")
        if name not in by_topic:
            raise ValueError(f"unknown topic {name!r} in {skill['id']}")
        by_topic[name].append(skill)

    indexes: dict[Path, str] = {}

    def index(path: Path, lines: list[str], budget: int = DETAIL_INDEX_BUDGET) -> None:
        body = "\n".join(lines) + "\n"
        if len(body.encode("utf-8")) > budget:
            raise ValueError(f"discovery index exceeds {budget} byte budget: {path.relative_to(plugin)}")
        indexes[path] = body

    root_lines = [
        "# Branchyard skills",
        "",
        "Choose a topic, then read only the relevant skill and supporting files. "
        "Keep your native planning and subagents.",
        "",
    ]
    for topic in topics:
        name = topic["id"]
        root_lines.append(f"- [{topic['title']}](topics/{name}/INDEX.md): {topic['description']}")
        topic_lines = [f"# {topic['title']}", "", topic["description"], "", "[All topics](../../INDEX.md)", ""]
        for skill in by_topic[name]:
            topic_lines.append(f"- [{skill['id']}](../../{skill['id']}/INDEX.md): {skill['description']}")
        index(skills_root / "topics" / name / "INDEX.md", topic_lines)
    if (skills_root / "upstream.lock.json").is_file():
        root_lines.extend(["", "[Upstream sources and licenses](upstream.lock.json)"])
    index(skills_root / "INDEX.md", root_lines, INDEX_BUDGET)

    metadata = {skill["id"]: skill for skill in catalog["skills"]}
    for directory in sorted(skills_root.iterdir()):
        if not directory.is_dir() or not (directory / "SKILL.md").is_file():
            continue
        files = files_under(directory, boundary)
        lines = [f"# {directory.name}", "", "Read [SKILL.md](SKILL.md), then open only the supporting file needed.", ""]
        for dependency in metadata.get(directory.name, {}).get("requires", []):
            lines.append(f"- Shared capability: [{dependency}](../{dependency}/INDEX.md)")
        groups: dict[str, list[tuple[str, str]]] = {"References": [], "Examples": [], "Schemas": [], "Tools": []}
        for path in files:
            relative = path.relative_to(directory)
            parts = relative.parts
            if relative.name == "INDEX.md":
                continue
            group = {"references": "References", "examples": "Examples", "schemas": "Schemas"}.get(parts[0])
            if parts[:3] == ("scripts", "branchyard_artifacts", "examples"):
                group = "Examples"
            elif parts[:3] == ("scripts", "branchyard_artifacts", "schemas"):
                group = "Schemas"
            elif len(parts) == 2 and parts[0] == "scripts" and path.suffix in {".py", ".sh", ".js", ".mjs"}:
                group = "Tools"
            if group:
                groups[group].append((relative.name, relative.as_posix()))
        for resource in metadata.get(directory.name, {}).get("resources", []):
            relative = Path(resource["path"])
            if relative.is_absolute():
                raise ValueError(f"skill resource must be a relative installed path: {relative}")
            target = directory / relative
            check_path(target, boundary)
            resolved = target.resolve(strict=True)
            if not resolved.is_relative_to(skills_root.resolve()) or not resolved.is_file():
                raise ValueError(f"skill resource is not an installed file: {resource['path']}")
            groups["References"].append((resource.get("description", relative.name), relative.as_posix()))
        for group, items in groups.items():
            if items:
                lines.extend(["", f"## {group}", ""])
                labels = {relative: label for label, relative in items}
                lines.extend(f"- [{label}]({relative})" for relative, label in labels.items())
        index(directory / "INDEX.md", lines)
    return indexes


def synchronize(root: Path, *, write: bool) -> list[str]:
    """Return stale generated paths, optionally rewriting those generated assets."""
    root = root.resolve(strict=True)
    plugin = root / "plugins/branchyard"
    verify_upstream(plugin / "skills", root)
    source = root / "sdk/python/branchyard_artifacts"
    target = plugin / "skills/artifact-tools/scripts/branchyard_artifacts"
    check_path(source, root)
    if not (source / "__init__.py").is_file():
        raise ValueError("canonical artifact package is missing")
    stale: list[str] = []

    def emit(path: Path, data: bytes) -> None:
        for ancestor in (path, *path.parents):
            if ancestor == root:
                break
            if ancestor.is_symlink():
                raise ValueError(f"generated destination is a symlink: {ancestor}")
        if path.is_file() and path.read_bytes() == data:
            return
        stale.append(path.relative_to(root).as_posix())
        if write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)

    canonical = {p.relative_to(source): p for p in files_under(source, root)}
    runtime_lock = root / "deploy/artifacts-requirements.lock"
    check_path(runtime_lock, root)
    if runtime_lock.is_file():
        emit(plugin / "skills/artifact-tools/scripts/requirements.lock", runtime_lock.read_bytes())
    for relative, path in canonical.items():
        emit(target / relative, path.read_bytes())
    if target.exists():
        for path in files_under(target, root):
            if path.relative_to(target) not in canonical:
                stale.append(path.relative_to(root).as_posix())
                if write:
                    path.unlink()
        if write:
            for path in sorted(target.rglob("*"), reverse=True):
                if path.is_dir() and not any(path.iterdir()):
                    path.rmdir()

    catalog_path = plugin / "capabilities.json"
    check_path(catalog_path, root)
    catalog = json.loads(catalog_path.read_text())
    seen: set[str] = set()
    for skill in catalog["skills"]:
        name = identifier(skill["id"], "skill id")
        if name in seen:
            raise ValueError(f"repeated skill id: {name!r}")
        seen.add(name)
        path = plugin / "skills" / name / "SKILL.md"
        check_path(path, root)
        text = path.read_text()
        front, marker, body = text.removeprefix("---\n").partition("\n---\n")
        if not text.startswith("---\n") or not marker:
            raise ValueError(f"skill lacks frontmatter: {path}")
        del front
        header = (
            "---\nname: " + name + "\ndescription: " + json.dumps(skill["description"], ensure_ascii=False) + "\n---\n"
        )
        emit(path, (header + body).encode())
    for skill in catalog["skills"]:
        for dependency in skill.get("requires", []):
            if dependency not in seen:
                raise ValueError(f"unknown dependency {dependency!r} in {skill['id']}")
    dependencies = {item["id"]: item.get("requires", []) for item in catalog["skills"]}

    def visit(name: str, ancestors: frozenset[str]) -> None:
        if name in ancestors:
            raise ValueError(f"cyclic skill dependency: {name}")
        for child in dependencies[name]:
            visit(child, ancestors | {name})

    for name in dependencies:
        visit(name, frozenset())

    indexes = navigation(plugin, catalog, root)
    for path, text in indexes.items():
        emit(path, text.encode())
    topics_root = plugin / "skills/topics"
    if topics_root.exists():
        for path in files_under(topics_root, root):
            if path.name == "INDEX.md" and path not in indexes:
                stale.append(path.relative_to(root).as_posix())
                if write:
                    path.unlink()
        if write:
            for directory in sorted(topics_root.rglob("*"), reverse=True):
                if directory.is_dir() and not any(directory.iterdir()):
                    directory.rmdir()

    code = [
        GENERATED,
        "//! Canonical skills shared by installation and managed-task provisioning.\n\n",
        "/// A skill's UTF-8 payload, relative to its installed directory.\n",
        "pub struct Skill {\n    /// Installed skill directory name.\n    pub name: &'static str,\n"
        "    /// Relative paths and exact file contents.\n"
        "    pub files: &'static [(&'static str, &'static str)],\n}\n\n",
        "/// The capability metadata and dependency graph.\n",
        'pub const CAPABILITIES: &str = include_str!("../../../plugins/branchyard/capabilities.json");\n\n',
        "/// Compact entry point shared by native installation and managed tasks.\n",
        'pub const INDEX: &str = include_str!("../../../plugins/branchyard/skills/INDEX.md");\n\n',
        "/// Pinned upstream source and license record, empty when no files are reused.\n",
    ]
    upstream_lock = plugin / "skills/upstream.lock.json"
    code.append(
        'pub const UPSTREAM_LOCK: &str = include_str!("../../../plugins/branchyard/skills/upstream.lock.json");\n\n'
        if upstream_lock.is_file()
        else 'pub const UPSTREAM_LOCK: &str = "";\n\n'
    )
    code.extend(
        [
            "/// Topic index paths relative to the installed skills directory, with their contents.\n",
            "#[rustfmt::skip]\npub const TOPIC_INDEXES: &[(&str, &str)] = &[\n",
        ]
    )
    for path in sorted(indexes):
        if not path.is_relative_to(topics_root):
            continue
        relative_index = path.relative_to(plugin / "skills").as_posix()
        include = "../../../" + path.relative_to(root).as_posix()
        code.append(f"    ({json.dumps(relative_index)}, include_str!({json.dumps(include)})),\n")
    code.extend(
        [
            "];\n\n",
            "/// Every shipped skill, including setup and delegation.\n",
            "#[rustfmt::skip]\npub const SKILLS: &[Skill] = &[\n",
        ]
    )
    for directory in sorted((plugin / "skills").iterdir()):
        if not directory.is_dir() or not (directory / "SKILL.md").is_file():
            continue
        code.append(f"    Skill {{ name: {json.dumps(directory.name)}, files: &[\n")
        for path in files_under(directory, root):
            relative_name = path.relative_to(directory).as_posix()
            include = "../../../" + path.relative_to(root).as_posix()
            code.append(f"        ({json.dumps(relative_name)}, include_str!({json.dumps(include)})),\n")
        code.append("    ] },\n")
    code.extend(
        [
            "];\n\n/// Find an installed skill by its exact name.\n",
            "pub fn skill(name: &str) -> Option<&'static Skill> {\n    SKILLS.iter().find(|s| s.name == name)\n}\n\n",
            "#[cfg(test)]\nmod tests {\n    use super::*;\n\n    #[test]\n    fn lookup_is_exact() {\n"
            "        for entry in SKILLS {\n"
            "            assert_eq!(skill(entry.name).map(|s| s.name), Some(entry.name));\n        }\n"
            '        assert!(skill("missing-skill").is_none());\n    }\n}\n',
        ]
    )
    emit(root / "crates/branchyard-provision/src/skills.rs", "".join(code).encode())
    return stale


def main() -> int:
    """Check generated assets by default, or rewrite with --write."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    try:
        stale = synchronize(ROOT, write=args.write)
    except (OSError, ValueError, KeyError) as error:
        parser.exit(1, f"artifact assets: {error}\n")
    if stale:
        print("\n".join(stale))
        return 0 if args.write else 1
    print("Artifact skill assets are current.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
