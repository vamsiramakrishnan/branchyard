#!/usr/bin/env python3
"""Generate the installed artifact-toolkit mirror and shared Rust skill assets."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATED = "// Generated by tools/artifact_assets.py; edit canonical skills or SDK sources.\n"


def check_path(path: Path, boundary: Path) -> None:
    """Refuse symlinks inside the trusted outer repository root."""
    if not path.is_relative_to(boundary):
        raise ValueError(f"asset path escapes the repository: {path}")
    for ancestor in (path, *path.parents):
        if ancestor == boundary:
            break
        if ancestor.is_symlink():
            raise ValueError(f"asset path is a symlink: {ancestor}")


def files_under(root: Path, boundary: Path) -> list[Path]:
    """Read only regular source files; refuse links rather than exporting their targets."""
    check_path(root, boundary)
    if not root.is_dir():
        raise ValueError(f"asset source is not a directory: {root}")
    found = []
    for path in sorted(root.rglob("*")):
        if "__pycache__" in path.parts or path.suffix == ".pyc":
            continue
        if path.is_symlink():
            raise ValueError(f"asset source is a symlink: {path}")
        if path.is_file():
            path.read_text(encoding="utf-8")
            found.append(path)
        elif not path.is_dir():
            raise ValueError(f"asset source is not a regular file or directory: {path}")
    return found


def synchronize(root: Path, *, write: bool) -> list[str]:
    """Return stale generated paths, optionally rewriting those generated assets."""
    root = root.resolve(strict=True)
    plugin = root / "plugins/branchyard"
    source = root / "sdk/python/branchyard_artifacts"
    target = plugin / "skills/artifact-tools/scripts/branchyard_artifacts"
    check_path(source, root)
    if not (source / "__init__.py").is_file():
        raise ValueError("canonical artifact package is missing")
    stale: list[str] = []

    def emit(path: Path, data: bytes) -> None:
        for ancestor in (path, *path.parents):
            if ancestor == root:
                break
            if ancestor.is_symlink():
                raise ValueError(f"generated destination is a symlink: {ancestor}")
        if path.is_file() and path.read_bytes() == data:
            return
        stale.append(path.relative_to(root).as_posix())
        if write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)

    canonical = {p.relative_to(source): p for p in files_under(source, root)}
    runtime_lock = root / "deploy/artifacts-requirements.lock"
    check_path(runtime_lock, root)
    if runtime_lock.is_file():
        emit(plugin / "skills/artifact-tools/scripts/requirements.lock", runtime_lock.read_bytes())
    for relative, path in canonical.items():
        emit(target / relative, path.read_bytes())
    if target.exists():
        for path in files_under(target, root):
            if path.relative_to(target) not in canonical:
                stale.append(path.relative_to(root).as_posix())
                if write:
                    path.unlink()
        if write:
            for path in sorted(target.rglob("*"), reverse=True):
                if path.is_dir() and not any(path.iterdir()):
                    path.rmdir()

    catalog_path = plugin / "capabilities.json"
    check_path(catalog_path, root)
    catalog = json.loads(catalog_path.read_text())
    seen: set[str] = set()
    for skill in catalog["skills"]:
        name = skill["id"]
        if name in seen or not name or any(c not in "abcdefghijklmnopqrstuvwxyz0123456789-" for c in name):
            raise ValueError(f"invalid or repeated skill id: {name!r}")
        seen.add(name)
        path = plugin / "skills" / name / "SKILL.md"
        check_path(path, root)
        text = path.read_text()
        front, marker, body = text.removeprefix("---\n").partition("\n---\n")
        if not text.startswith("---\n") or not marker:
            raise ValueError(f"skill lacks frontmatter: {path}")
        del front
        header = (
            "---\nname: " + name + "\ndescription: " + json.dumps(skill["description"], ensure_ascii=False) + "\n---\n"
        )
        emit(path, (header + body).encode())
    for skill in catalog["skills"]:
        for dependency in skill.get("requires", []):
            if dependency not in seen:
                raise ValueError(f"unknown dependency {dependency!r} in {skill['id']}")
    dependencies = {item["id"]: item.get("requires", []) for item in catalog["skills"]}

    def visit(name: str, ancestors: frozenset[str]) -> None:
        if name in ancestors:
            raise ValueError(f"cyclic skill dependency: {name}")
        for child in dependencies[name]:
            visit(child, ancestors | {name})

    for name in dependencies:
        visit(name, frozenset())

    code = [
        GENERATED,
        "//! Canonical skills shared by installation and managed-task provisioning.\n\n",
        "/// A skill's UTF-8 payload, relative to its installed directory.\n",
        "pub struct Skill {\n    /// Installed skill directory name.\n    pub name: &'static str,\n"
        "    /// Relative paths and exact file contents.\n"
        "    pub files: &'static [(&'static str, &'static str)],\n}\n\n",
        "/// The document capability metadata and dependency graph.\n",
        'pub const CAPABILITIES: &str = include_str!("../../../plugins/branchyard/capabilities.json");\n\n',
        "/// Every shipped skill, including setup and delegation.\n",
        "#[rustfmt::skip]\npub const SKILLS: &[Skill] = &[\n",
    ]
    for directory in sorted((plugin / "skills").iterdir()):
        if not directory.is_dir() or not (directory / "SKILL.md").is_file():
            continue
        code.append(f"    Skill {{ name: {json.dumps(directory.name)}, files: &[\n")
        for path in files_under(directory, root):
            relative_name = path.relative_to(directory).as_posix()
            include = "../../../" + path.relative_to(root).as_posix()
            code.append(f"        ({json.dumps(relative_name)}, include_str!({json.dumps(include)})),\n")
        code.append("    ] },\n")
    code.extend(
        [
            "];\n\n/// Find an installed skill by its exact name.\n",
            "pub fn skill(name: &str) -> Option<&'static Skill> {\n    SKILLS.iter().find(|s| s.name == name)\n}\n\n",
            "#[cfg(test)]\nmod tests {\n    use super::*;\n\n    #[test]\n    fn lookup_is_exact() {\n"
            "        for entry in SKILLS {\n"
            "            assert_eq!(skill(entry.name).map(|s| s.name), Some(entry.name));\n        }\n"
            '        assert!(skill("missing-skill").is_none());\n    }\n}\n',
        ]
    )
    emit(root / "crates/branchyard-provision/src/skills.rs", "".join(code).encode())
    return stale


def main() -> int:
    """Check generated assets by default, or rewrite with --write."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    try:
        stale = synchronize(ROOT, write=args.write)
    except (OSError, ValueError, KeyError) as error:
        parser.exit(1, f"artifact assets: {error}\n")
    if stale:
        print("\n".join(stale))
        return 0 if args.write else 1
    print("Artifact skill assets are current.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
